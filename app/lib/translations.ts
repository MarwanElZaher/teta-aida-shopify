export function useTranslation() {
    const root = useMatches().find((match) => match.id === 'root');
    const locale = (root?.data as any)?.locale || { language: 'EN', country: 'EG', pathPrefix: '' };
    const language = locale.language as keyof typeof TRANSLATIONS;

    return {
        t: (key: string) => {
            const keys = key.split('.');
            let value: any = TRANSLATIONS[language] || TRANSLATIONS['EN'];
            for (const k of keys) {
                value = value?.[k];
            }
            return value || key;
        },
        locale,
        isRtl: language === 'AR',
    };
}
